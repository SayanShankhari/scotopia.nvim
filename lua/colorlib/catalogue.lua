-----------------------
-- Unified Lookup Cache
-----------------------

local cache = {};

-- 1. Flatten nested sub-tables (e.g., variant_color: "dark_red")
for color_name, variants in pairs (C.basic) do
  if type (variants) == "table" then
    for variant_type, color_code in pairs (variants) do
      if variant_type == "base" then
        -- Optional convenience: allows both C.red and C.base_red
        cache [color_name] = color_code;
        cache ["base_" .. color_name] = color_code;
      else
        cache [variant_type .. "_" .. color_name] = color_code;
      end
    end
  else
    -- Fallback if basic also contains flat keys
    cache [color_name] = variants;
  end
end

-- 2. Import flat sub-tables into cache (in order of priority)
local flat_sources = { C.tailwindcss, C.htmlcolorcode }

for _, source_tbl in ipairs (flat_sources) do
  for key, hex_val in pairs (source_tbl) do
    -- Only set if not already set (respects priority order)
    if cache [key] == nil then
      cache [key] = hex_val
    end
  end
end

-- 3. Attach pre-calculated cache to Catalogue as metatable
setmetatable (C, { __index = cache });


